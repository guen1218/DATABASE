SELECT BRAND_CD, INVOICE_NO, LINE_NO, ITEM_CD, ORDER_QTY,
  CASE WHEN ORDER_QTY BETWEEN 1 AND 2 THEN '하'
       WHEN ORDER_QTY BETWEEN 3 AND 4 THEN '중'
       WHEN ORDER_QTY >= 5            THEN '상' 
   END AS GRADE
  FROM A_OUT_D
 WHERE BRAND_CD = '1001'
 ORDER BY CASE ITEM_CD WHEN 'C' THEN 1 ELSE 2 END, ITEM_CD, ORDER_QTY DESC;
 
SELECT OUTBOUND_DATE
      ,COUNT(*) AS INVOICE_CNT
      ,COUNT(CASE WHEN OUT_TYPE_DIV LIKE 'M1%' THEN '1' ELSE NULL END) AS M1_CNT
      ,COUNT(CASE WHEN OUT_TYPE_DIV LIKE 'M2%' THEN '1' ELSE NULL END) AS M2_CNT
  FROM LO_OUT_M
 WHERE OUTBOUND_DATE BETWEEN '2019-09-01' AND '2019-09-19'
   AND OUT_BOX_DIV LIKE 
       CASE :COND
       WHEN '0' THEN '%'
       WHEN '1' THEN 'D%'
       WHEN '2' THEN 'F%'
       ELSE ' ' END
 GROUP BY OUTBOUND_DATE
;

