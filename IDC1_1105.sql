SELECT INVOICE_NO, LINE_NO, ITEM_CD, ITEM_NM, ORDER_QTY
  FROM LO_OUT_D
 WHERE INVOICE_NO = '346724706214'
 ORDER BY CASE :SORT_TYPE
          WHEN '1' THEN LINE_NO
          WHEN '2' THEN ORDER_QTY
          END,
          CASE WHEN :SORT_TYPE = '2' 
          THEN LINE_NO END
;

SELECT M.BRAND_CD, M.OUTBOUND_DATE, D.INVOICE_NO, D.LINE_NO, D.ORDER_QTY
  FROM A_OUT_D D
  JOIN A_OUT_M M 
    ON M.INVOICE_NO = D.INVOICE_NO
   AND M.BRAND_CD = D.BRAND_CD
 WHERE M.OUTBOUND_DATE BETWEEN '2023-01-03' AND '2023-01-04'
   AND D.ITEM_CD IN ('B', 'D')
;

SELECT M.BRAND_CD, M.OUTBOUND_DATE, D.INVOICE_NO, D.LINE_NO, SUM(D.ORDER_QTY)
  FROM A_OUT_M M
  JOIN A_OUT_D D
    ON M.INVOICE_NO = D.INVOICE_NO
   AND M.BRAND_CD = D.BRAND_CD
 WHERE M.OUTBOUND_DATE BETWEEN '2023-01-03' AND '2023-01-04'
   AND D.ITEM_CD IN ('B', 'D')
 GROUP BY M.BRAND_CD, M.OUTBOUND_DATE, D.INVOICE_NO, D.LINE_NO
;

SELECT *
  FROM(
        SELECT M.INVOICE_NO, M.ORDER_NM
          FROM A_OUT_M M
          JOIN A_OUT_D D
            ON M.INVOICE_NO = D.INVOICE_NO
           AND M.BRAND_CD   = D.BRAND_CD
         GROUP BY M.INVOICE_NO, M.ORDER_NM
         ORDER BY SUM(D.ORDER_QTY) DESC 
     )
 WHERE ROWNUM = 1
;

SELECT D.BRAND_CD, M.OUTBOUND_DATE, D.INVOICE_NO, D.ITEM_CD, A.ITEM_NM, D.ORDER_QTY
  FROM A_OUT_D D
  JOIN A_OUT_M M
    ON M.INVOICE_NO = D.INVOICE_NO
   AND M.BRAND_CD   = D.BRAND_CD
  JOIN A_ITEM A
    ON A.ITEM_CD  = D.ITEM_CD
   AND A.BRAND_CD = D.BRAND_CD
 WHERE M.OUTBOUND_DATE BETWEEN '2023-01-01' AND '2023-01-04'
   AND D.ORDER_QTY >= 3
;

SELECT D.BRAND_CD, A.ITEM_NM, SUM(D.ORDER_QTY) AS SUM_QTY
  FROM A_OUT_D D
  JOIN A_OUT_M M
    ON M.INVOICE_NO = D.INVOICE_NO
   AND M.BRAND_CD   = D.BRAND_CD
  JOIN A_ITEM A
    ON A.ITEM_CD  = D.ITEM_CD
   AND A.BRAND_CD = D.BRAND_CD
 GROUP BY D.BRAND_CD, A.ITEM_NM
 ORDER BY BRAND_CD
;
 
SELECT BRAND_CD, ITEM_NM, SUM_QTY, 
       TRUNC(SUM_QTY / QTY_IN_BOX) AS BOX, 
       MOD(SUM_QTY, QTY_IN_BOX) AS NATGAE
  FROM(
        SELECT D.BRAND_CD, A.ITEM_NM, SUM(D.ORDER_QTY) AS SUM_QTY, QTY_IN_BOX
          FROM A_OUT_D D
          JOIN A_OUT_M M
            ON M.INVOICE_NO = D.INVOICE_NO
           AND M.BRAND_CD   = D.BRAND_CD
          JOIN A_ITEM A
            ON A.ITEM_CD  = D.ITEM_CD
           AND A.BRAND_CD = D.BRAND_CD
         WHERE M.OUTBOUND_DATE BETWEEN '2023-01-01' AND '2023-01-04'
         GROUP BY D.BRAND_CD, A.ITEM_NM, QTY_IN_BOX
         ORDER BY BRAND_CD
     )
;
 
SELECT BRAND_CD, ITEM_NM, SUM_QTY, 
       TRUNC(SUM_QTY / QTY_IN_BOX) AS BOX, 
       MOD(SUM_QTY, QTY_IN_BOX) AS NATGAE
  FROM(
        SELECT D.BRAND_CD, A.ITEM_NM, SUM(D.ORDER_QTY) AS SUM_QTY, QTY_IN_BOX
          FROM A_OUT_D D
          JOIN A_OUT_M M ON  M.INVOICE_NO = D.INVOICE_NO 
                         AND M.BRAND_CD   = D.BRAND_CD
          JOIN A_ITEM A  ON  A.ITEM_CD    = D.ITEM_CD
                         AND A.BRAND_CD   = D.BRAND_CD
         WHERE M.OUTBOUND_DATE BETWEEN '2023-01-01' AND '2023-01-04'
         GROUP BY D.BRAND_CD, A.ITEM_NM, QTY_IN_BOX
         ORDER BY TRUNC(SUM_QTY / QTY_IN_BOX) DESC
     ) 
 WHERE ROWNUM <=3
;