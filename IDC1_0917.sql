SELECT D2.BRAND_CD, D2.ITEM_CD, D2.ORDER_QTY, 
       TRUNC(D2.ORDER_QTY / :BOX_IPSU) AS BOX_SU, 
       MOD(D2.ORDER_QTY, :BOX_IPSU) AS BOX_NATGAE
  FROM (
        SELECT D1.BRAND_CD, D1.ITEM_CD, SUM(D1.ORDER_QTY) AS ORDER_QTY
          FROM A_OUT_D D1
         GROUP BY D1.BRAND_CD, D1.ITEM_CD
         ORDER BY ORDER_QTY DESC
        ) D2
 WHERE ROWNUM <= 3;