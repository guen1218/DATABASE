SELECT TO_DATE(:OUTBOUND_DATE, 'YYYY-MM-DD') + NO AS ORG_DATE
  FROM CS_NO
 WHERE NO <= :DAYS;
 
SELECT LEVEL AS NO
  FROM DUAL
CONNECT BY LEVEL <= 10;

SELECT *
  FROM CS_NO
 WHERE NO <= TO_DATE(:TO_DATE, 'YYYY-MM-DD') - TO_DATE(:FROM_DATE, 'YYYY-MM-DD') + 1;
 
SELECT TO_DATE(:FROM_DATE, 'YYYY-MM-DD') + NO - 1
 FROM CS_NO
WHERE NO <= TO_DATE(:TO_DATE, 'YYYY-MM-DD') - TO_DATE(:FROM_DATE, 'YYYY-MM-DD') + 1;


SELECT *
  FROM (
        SELECT TO_DATE(:OUTBOUND_DATE, 'YYYY-MM-DD') + NO AS ORG_DATE
          FROM CS_NO
         WHERE NO <= :DAYS
         ) M1
 WHERE EXISTS (
               SELECT 'TLQKF'
                 FROM LO_OUT_M S1
                WHERE S1.OUTBOUND_DATE = M1.ORG_DATE
               );
               
